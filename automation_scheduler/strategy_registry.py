def _strategy(
    strategy_id: str,
    strategy_name: str,
    strategy_family: str,
    *,
    asset_types_supported: list[str],
    market_types_supported: list[str],
    allowed_contexts: list[str] | None = None,
    forbidden_contexts: list[str] | None = None,
    maturity_status: str = "research_only",
    enabled: bool = True,
    affects_review_queue: bool = False,
    affects_ranking: bool = False,
    affects_execution: bool = False,
    required_inputs: list[str] | None = None,
    optional_inputs: list[str] | None = None,
    minimum_sample_size: int = 30,
    current_sample_size: int = 0,
    outcome_coverage: float = 0.0,
    calibration_status: str = "insufficient_data",
    performance_status: str = "unknown",
    promotion_status: str = "not_ready",
    demotion_status: str = "none",
    blocked_reason: str | None = None,
    safety_review_status: str = "locked_read_only",
) -> dict[str, Any]:
    maturity = maturity_status if maturity_status in MATURITY_STATUSES else "blocked_safety_review"
    if strategy_family not in STRATEGY_FAMILIES:
        maturity = "blocked_missing_dependency"
    record = {
        "strategy_id": strategy_id,
        "strategy_name": strategy_name,
        "strategy_family": strategy_family,
        "asset_types_supported": asset_types_supported,
        "market_types_supported": market_types_supported,
        "allowed_contexts": allowed_contexts or [],
        "forbidden_contexts": forbidden_contexts or [],
        "maturity_status": maturity,
        "enabled": bool(enabled),
        "affects_review_queue": bool(affects_review_queue),
        "affects_ranking": bool(affects_ranking),
        "affects_execution": False,
        "required_inputs": required_inputs or [],
        "optional_inputs": optional_inputs or [],
        "minimum_sample_size": int(minimum_sample_size),
        "current_sample_size": int(current_sample_size),
        "outcome_coverage": float(outcome_coverage or 0.0),
        "calibration_status": calibration_status,
        "performance_status": performance_status,
        "promotion_status": promotion_status,
        "demotion_status": demotion_status,
        "blocked_reason": blocked_reason,
        "safety_review_status": safety_review_status,
        "future_execution_eligible": False,
        "currently_executable": False,
        **locked_safety_flags(),
    }
    record["provider_write"] = False
    record["execution_allowed"] = False
    record["live_execution_enabled"] = False
    record["auto_execution"] = False
    return record


