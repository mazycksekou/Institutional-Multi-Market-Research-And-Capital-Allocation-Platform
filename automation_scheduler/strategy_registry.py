def get_strategy_registry(overrides: Mapping[str, Mapping[str, Any]] | None = None) -> dict[str, dict[str, Any]]:
    registry = get_default_strategy_registry()
    for strategy_id, patch in dict(overrides or {}).items():
        if strategy_id in registry and isinstance(patch, Mapping):
            registry[strategy_id] = normalize_strategy_record({**registry[strategy_id], **dict(patch)})
    return registry


def normalize_strategy_record(record: Mapping[str, Any]) -> dict[str, Any]:
    row = dict(record)
    row["maturity_status"] = row.get("maturity_status") if row.get("maturity_status") in MATURITY_STATUSES else "blocked_safety_review"
    row["provider_write"] = False
    row["execution_allowed"] = False
    row["live_execution_enabled"] = False
    row["auto_execution"] = False
    row["auto_execution_enabled"] = False
    row["affects_execution"] = False
    row["future_execution_eligible"] = False
    row["currently_executable"] = False
    for key, value in locked_safety_flags().items():
        if key in {
            "provider_write",
            "execution_allowed",
            "live_execution_enabled",
            "auto_execution",
            "auto_execution_enabled",
            "human_approval_required",
            "owner_approval_required",
        }:
            row[key] = value
    return row


def compact_strategy_registry(registry: Mapping[str, Mapping[str, Any]] | None = None) -> dict[str, Any]:
    reg = registry if registry is not None else get_strategy_registry()
    strategies = [normalize_strategy_record(row) for row in reg.values()]
    return {
        "ok": True,
        "status": "strategy_registry",
        "total_strategies": len(strategies),
        "strategies": sorted(strategies, key=lambda row: row["strategy_id"]),
        **locked_safety_flags(),
    }
