def build_policy_queries_for_group(
    *,
    sport_group: str,
    sport_label: str,
    extra_queries: list[str] | None = None,
) -> dict[str, Any]:
    candidates = [candidate for candidate in completed_sports_candidate_source_catalog() if candidate["sport_group"] == sport_group]
    query_rows: list[dict[str, Any]] = []
    families = (
        ("exact_source_name", lambda c: f"{sport_label} {c['source_name']}"),
        ("exact_domain_policy", lambda c: f"{c['source_domain']} terms robots license"),
        ("source_terms", lambda c: f"{c['source_name']} terms of use"),
        ("source_robots", lambda c: f"{c['source_name']} robots.txt"),
        ("source_license", lambda c: f"{c['source_name']} license"),
        ("source_api_docs", lambda c: f"{c['source_name']} api docs"),
        ("source_data_dictionary", lambda c: f"{c['source_name']} data dictionary"),
        ("source_attribution", lambda c: f"{c['source_name']} attribution"),
        ("source_commercial_use", lambda c: f"{c['source_name']} commercial use"),
        ("source_automation", lambda c: f"{c['source_name']} automated access"),
    )
    for candidate in candidates:
        for family, builder in families:
            query_rows.append(
                {
                    "sport_group": sport_group,
                    "sport_label": sport_label,
                    "source_id": candidate["source_id"],
                    "source_name": candidate["source_name"],
                    "domain": candidate["source_domain"],
                    "field_group": candidate["field_group"],
                    "query_family": family,
                    "query": builder(candidate),
                }
            )
    for query in extra_queries or []:
        query_rows.append(
            {
                "sport_group": sport_group,
                "sport_label": sport_label,
                "source_id": "",
                "source_name": sport_label,
                "domain": "",
                "field_group": "supplemental",
                "query_family": "extra_query",
                "query": query,
            }
        )
    return {
        "ok": True,
        "status": "ok",
        "sport_group": sport_group,
        "sport_label": sport_label,
        "query_rows": query_rows,
        "query_count": len(query_rows),
        "query_families": sorted({row["query_family"] for row in query_rows}),
        "provider_write": False,
        "execution_allowed": False,
        "raw_payload_included": False,
        "secrets_included": False,
    }
